// @ts-check
import { readFileSync } from 'node:fs'

import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import starlightLlmsTxt from 'starlight-llms-txt'

// Read rather than `import ... with { type: 'json' }`: the config is loaded by Astro's own config
// loader, and a plain `fs` read has no import-attribute compatibility to depend on.
const apiNav = JSON.parse(
  readFileSync(new URL('./src/generated/api-nav.json', import.meta.url), 'utf8'),
)

// One source, two builds. The public site is served from a domain root; the copy shipped inside the
// server image is served from the `/docs` sub-path that `LANRURUGI_DOCS_DIR` already provides. Only
// `base` differs between them — the sources, and the generated API document they render, are the
// same bytes. Building twice from one source is what stops the published site and the offline copy
// from drifting into two independently maintained documents.
const base = process.env.DOCS_BASE ?? '/'
const site = process.env.DOCS_SITE_URL

/** @type {import('astro/config').AstroUserConfig} */
// Where the SDK reference lives. Its own Cloudflare Pages project in production, and a sibling
// directory of the composed `/docs` tree inside the server image — so the same page links correctly
// in both, and neither build needs to know about the other's hosting.
const sdkUrl = process.env.DOCS_SDK_URL ?? `${base.replace(/\/$/, '')}/sdk/`

// Swagger UI: its own Pages project in production, `<base>swagger/` inside the server image.
const swaggerUrl = process.env.DOCS_SWAGGER_URL ?? `${base.replace(/\/$/, '')}/swagger/`
// Absolute when the public site URL is known, so the links in llms.txt work outside a browser.
const docsRoot = `${site ? site.replace(/\/$/, '') : ''}${base.replace(/\/?$/, '/')}`

// llms.txt (https://llmstxt.org) for AI tools: the docs as Markdown, plus pointers to the two
// machine-readable references that describe the API and the plugin contract exactly. The plugin
// needs `site`, so only the public build has it; the offline copy in the server image does not.
const llmsTxt = site && starlightLlmsTxt({
  projectName: 'LANrurugi',
  description:
    'A self-hosted library server for manga and comics that also reads PDF, EPUB, MOBI, DjVu, FB2 and TXT books. It started from LANraragi, can open an existing LANraragi library directly, and is rewritten in Rust + React with on-page manga translation, similar-work recommendations and AI plugin generation.',
  details: [
    'The documentation is written in Simplified Chinese (the default locale, no path prefix) and English (under `/en/`); both cover the same pages. The sets below split it by language and by guides versus API reference.',
    '',
    `**HTTP API.** Every endpoint a LANrurugi server serves is described in one OpenAPI 3.1 document, [openapi.json](${docsRoot}openapi.json), generated from the server's own route registrations, so it lists exactly what the server serves. Endpoints shared with LANraragi keep that project's field-level documentation and stay compatible with its clients. Authenticate with an API token created in the instance's settings, sent as \`Authorization: Bearer <token>\`. The same document is browsable in [Swagger UI](${swaggerUrl}) and, one page per group, in this site's API reference.`,
    '',
    `**Plugin SDK.** Plugins are single TypeScript files run by the server in their own Deno subprocess with only the network and file permissions they declare. Each exports \`pluginInfo()\` plus one entry point for its type: \`execMetadata\` (metadata), \`execLogin\` (login), \`execDownload\` (download) or \`runScript\` (script). The [SDK reference](${sdkUrl}) documents every type involved, generated by \`deno doc\` from the TypeScript the plugin runtime loads; [plugin-sdk.json](${sdkUrl.replace(/\/?$/, '/')}plugin-sdk.json) is the same reference as JSON. Start from the [plugin getting-started guide](${docsRoot}en/plugin/getting-started/).`,
  ].join('\n'),
  customSets: [
    { label: 'Guides (English)', paths: ['en/index*', 'en/guide/**', 'en/plugin/**'], description: 'installation, usage and plugin authoring' },
    { label: 'API reference (English)', paths: ['en/api/**'], description: 'every endpoint, one page per group' },
    { label: 'Guides (Simplified Chinese)', paths: ['index*', 'guide/**', 'plugin/**'], description: '安装、使用与插件开发' },
    { label: 'API reference (Simplified Chinese)', paths: ['api/**'], description: '全部端点，每组一页' },
  ],
  optionalLinks: [
    { label: 'OpenAPI document', url: `${docsRoot}openapi.json`, description: 'the complete HTTP API as OpenAPI 3.1 JSON' },
    { label: 'Plugin SDK reference (JSON)', url: `${sdkUrl.replace(/\/?$/, '/')}plugin-sdk.json`, description: 'every plugin-facing type, from deno doc' },
    { label: 'Source code', url: 'https://github.com/thelastfantasy/LANrurugi', description: 'MIT licensed' },
  ],
  // The abridged set leaves out the API pages: openapi.json describes the same endpoints exactly.
  exclude: ['api/**', 'en/api/**'],
})

export default defineConfig({
  ...(site ? { site } : {}),
  base,
  // Pages and Starlight both serve directory URLs (`/guide/sharing/`, `/en/`), and Cloudflare
  // Pages 308-redirects the slash-less form to it. Declaring that here is what makes generated
  // links match: without it the language switcher emitted `href="/en"`, which Search Console then
  // reported as "Page with redirect".
  trailingSlash: 'always',
  // `DOCS_SDK_URL` has no `PUBLIC_` prefix, so it is not in `import.meta.env` by default; injecting
  // it here is what lets the content pages read it (see `plugin/sdk.mdx`).
  vite: {
    define: { 'import.meta.env.DOCS_SDK_URL': JSON.stringify(sdkUrl) },
  },
  integrations: [
    starlight({
      title: 'LANrurugi',
      description:
        '以漫画为主、也能读 PDF / EPUB 等电子书的自托管书库，以 LANraragi 为起点、用 Rust + React 大幅改造与强化。这里放安装、使用、插件开发与 HTTP API 参考。',
      // Two locales, each with its own content directory: `src/content/docs/` is the default
      // (Simplified Chinese, served without a path prefix) and `src/content/docs/en/` is English.
      // Declaring both is what puts the language switcher in the header.
      locales: {
        root: { label: '简体中文', lang: 'zh-CN' },
        en: { label: 'English', lang: 'en' },
      },
      // Rendered by the `SocialIcons` override below as text links. Kept in the config because it is
      // the framework's declared place for these, and the override asserts every entry here is
      // actually rendered — a configured link that silently never appears is its own bug.
      // The product's own icon, copied from the frontend by `prepare-static-assets.mjs`.
      logo: { src: './src/generated/logo.svg' },
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/thelastfantasy/LANrurugi' },
      ],
      // The sidebar is explicit rather than auto-generated, and every group carries `translations`
      // so the headings follow the reader's chosen language. Group *names* for the API section come
      // from `docs/api/tag-names.json` via the generated nav, so a new API group cannot appear as a
      // raw module name in the sidebar.
      sidebar: [
        {
          label: '用户指南',
          translations: { en: 'User Guide' },
          items: [
            { label: '安装（Docker / NAS）', translations: { en: 'Install (Docker / NAS)' }, slug: 'guide/install' },
            { label: '原生安装（Linux / macOS / FreeBSD）', translations: { en: 'Native install (Linux / macOS / FreeBSD)' }, slug: 'guide/install-native' },
            { label: '反向代理', translations: { en: 'Reverse proxy' }, slug: 'guide/reverse-proxy' },
            { label: '快速开始', translations: { en: 'Quickstart' }, slug: 'guide/quickstart' },
            { label: '支持的格式', translations: { en: 'Supported formats' }, slug: 'guide/formats' },
            { label: '分享与导入', translations: { en: 'Sharing and importing' }, slug: 'guide/sharing' },
            { label: '用文档站测试 API', translations: { en: 'Testing the API from these docs' }, slug: 'guide/api-testing' },
            { label: '给 AI 工具用的 llms.txt', translations: { en: 'llms.txt for AI tools' }, slug: 'guide/llms-txt' },
          ],
        },
        {
          label: '插件开发',
          translations: { en: 'Writing Plugins' },
          items: [
            { label: '入门', translations: { en: 'Getting started' }, slug: 'plugin/getting-started' },
            // A content page rather than `link: '<base>sdk/'`: Starlight locale-prefixes sidebar
            // `link` values, so a raw path produced `/en/sdk/` — 43 dead links, since the
            // generated reference is a `public/` asset and exists only at `/sdk/`. The page links
            // to it with `import.meta.env.BASE_URL`, which is correct under any base.
            { label: 'SDK 参考', translations: { en: 'SDK Reference' }, slug: 'plugin/sdk' },
          ],
        },
        {
          label: 'API 文档',
          translations: { en: 'API Documentation' },
          // One page per API group, generated from the OpenAPI document by
          // `scripts/generate-api-pages.mjs`. Each page renders its operations as real headings, so
          // Starlight's own right-hand outline lists them — the same structure the reference site
          // uses, and the reason a single embedded API viewer was not good enough.
          items: apiNav.map((group) => ({
            label: group.zh,
            translations: { en: group.en },
            slug: `api/${group.slug}`,
          })),
        },
      ],
      // Palette shared with the homepage, Swagger UI and SDK pages, then Starlight's mapping onto it.
      customCss: ['./theme/tokens.css', './src/styles/custom.css', './src/styles/theme.css'],
      plugins: llmsTxt ? [llmsTxt] : [],
      components: {
        // Text links instead of icon-only ones; see the component's own docs for which of the
        // reference site's four top-bar links this project can honestly offer.
        SocialIcons: './src/components/SocialIcons.astro',
        // The homepage's E-H / EX palette switch instead of the dark/light/auto dropdown.
        ThemeSelect: './src/components/ThemeSelect.astro',
        // Starlight's search plus an empty state (example queries, popular pages).
        Search: './src/components/Search.astro',
      },
    }),
  ],
})
